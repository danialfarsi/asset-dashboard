class Command(BaseCommand):
    help = 'Seed data for Maturity IAMS'

    @transaction.atomic
    def handle(self, *args, **options):
        # ۱. مؤلفه‌ها
        self.stdout.write('📦 Creating components...')
        for comp_data in COMPONENTS:
            comp, created = MaturityComponent.objects.update_or_create(
                number=comp_data['number'],
                defaults=comp_data
            )
            if created:
                self.stdout.write(f'   ✅ {comp.code}: {comp.name}')

        # ۲. پروفایل‌ها
        self.stdout.write('📦 Creating weight profiles...')
        for profile_data in PROFILES:
            profile_type = profile_data['profile_type']
            profile_data['component_weights'] = COMPONENT_WEIGHTS[profile_type]
            
            profile, created = MaturityWeightProfile.objects.update_or_create(
                profile_type=profile_type,
                defaults=profile_data
            )
            if created:
                self.stdout.write(f'   ✅ {profile.name}')

        # ۳. پرسش‌ها
        self.stdout.write('📦 Creating questions...')
        created_count = 0
        for number, code, text, comp_number in QUESTIONS:
            component = None
            if comp_number:
                component = MaturityComponent.objects.filter(number=comp_number).first()
            
            is_anchor = code in ['Q-49-A', 'Q-50-B']
            
            _, created = MaturityQuestion.objects.update_or_create(
                code=code,
                defaults={
                    'number': number,
                    'text': text,
                    'component': component,
                    'question_type': 'anchor' if is_anchor else 'measure',
                }
            )
            if created:
                created_count += 1
        
        self.stdout.write(f'   ✅ {created_count} پرسش ساخته شد')

        # ۴. آمار نهایی
        self.stdout.write('')
        self.stdout.write('=' * 50)
        self.stdout.write(f'✅ Components: {MaturityComponent.objects.count()}')
        self.stdout.write(f'✅ Profiles: {MaturityWeightProfile.objects.count()}')
        self.stdout.write(f'✅ Questions: {MaturityQuestion.objects.count()}')
        self.stdout.write('=' * 50)
